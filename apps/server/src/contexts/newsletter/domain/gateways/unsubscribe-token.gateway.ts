/**
 * メール本文の配信停止リンクに載せる、ログイン不要の本人証明。
 *
 * ## なぜログイン不要にするのか
 *
 * 配信停止は「もう読みたくない」人がする操作で、その人はたいていログインしない。
 * ログインを挟むと実質「止められない」に等しくなり、迷惑メール報告のほうが早い。
 * Gmail / Yahoo の一括送信者要件（RFC 8058 のワンクリック配信停止）も、
 * 認証を挟まないエンドポイントを前提にしている。
 *
 * ## 何を守るか
 *
 * 守りたいのは「第三者が他人を勝手に配信停止させられないこと」だけ。
 * トークンは user_id の署名で、**推測できないこと** が要件。DB に持たず署名で
 * 表現するのは、発行のたびに行を作らずに済み、失効管理も要らないため
 * （秘密鍵を替えれば全部まとめて無効になる）。
 */
export interface UnsubscribeTokenGateway {
  /**
   * 署名付きトークンを作る。秘密鍵が無ければ
   * {@link UnsubscribeTokenUnavailableError} を投げる。
   */
  issue(userId: string): string;

  /** 署名が正しければ user_id を、壊れていれば null を返す。 */
  verify(token: string): string | null;
}

/**
 * 署名鍵が無い状態。
 *
 * **配信停止リンクを作れないなら一斉メールを送ってはいけない。** 止める口の
 * 無い一斉配信は、受け取った人に迷惑メール報告以外の選択肢を残さない
 * （そして報告が積もると送信ドメイン全体の到達率が落ちる）。
 */
export class UnsubscribeTokenUnavailableError extends Error {}
