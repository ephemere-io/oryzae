/**
 * シートの「外側（板の段）」と「内側（中身の送り）」の段階構造。
 *
 * ネイティブのシート（Google マップ・Apple の地図）は、外と内を**同時には**動かさない。
 * 段階になっていて、指を置いた瞬間にどちらの持ち主かが決まり、**離すまで変わらない**。
 * 途中で持ち主が入れ替わると「操作量と挙動が合わない」「イベントが絡まっている」と感じる。
 *
 * | 段 | 触れた場所 | 触れた瞬間の scrollTop | その指で板を動かせるか |
 * | --- | --- | --- | --- |
 * | いちばん高い段では**ない** | どこでも | — | 動かせる（内側は送れない） |
 * | いちばん高い段 | 見出しの行 | — | 動かせる |
 * | いちばん高い段 | 中身 | 0 より大きい（読んでいる途中） | 動かせない |
 * | いちばん高い段 | 中身 | 0（上端） | 動かせる |
 *
 * 最後の行だけは向きも効く: 上端で上へ送ろうとしても送る先が無いので何も起きず、
 * 下へ引けば板が縮む。ここはブラウザの既定の振る舞いに任せてよい。
 *
 * 「読み終えて上端に着いた指」で板が動かないのは 3 行目のため。一度離すと 4 行目になり、
 * 次の指で板が縮む。オーナーの言葉: 「内側のスクロールが終わったら一度タップを離した後に
 * 外側のスクロールに移行できる」。
 */

export interface SheetTouch {
  /** 板がいちばん高い段に居るか。 */
  atHighest: boolean;
  /** 触れたのが中身の箱か（見出しの行なら false）。 */
  onContent: boolean;
  /** 触れた瞬間の中身の `scrollTop`。 */
  scrollTop: number;
}

/**
 * この指で板（外側）を動かしてよいか。**触れた瞬間に 1 回だけ決める。**
 *
 * 「動かしてよい」は「必ず動く」ではない。上端で上へ引くように、動かす先が無ければ何も起きない。
 */
export function canDragSheet({ atHighest, onContent, scrollTop }: SheetTouch): boolean {
  if (!atHighest) return true;
  if (!onContent) return true;
  return scrollTop <= 0;
}

/**
 * 中身を送れるか。**いちばん高い段だけ。**
 *
 * 段の途中で送れると、板を伸ばしている最中に中身が流れて、どちらを動かしているのか分からなくなる
 * （実機: 中くらいの段で強く押してから引くと中身が動いた）。判定でも待ち時間でもなく
 * `overflow-y` で決めるので、ブラウザがそもそも送らない。
 */
export function contentScrolls(atHighest: boolean): boolean {
  return atHighest;
}
